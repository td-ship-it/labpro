/**
 * Bộ ghi file .xlsx tối giản, không phụ thuộc thư viện ngoài.
 * Mọi chuỗi được lưu dưới dạng UTF-8 trong XML, nên Excel hiển thị đúng tiếng Việt
 * (khác với CSV, vốn bị Excel đoán sai bảng mã và làm lỗi font).
 */

export type XlsxStyle = 'normal' | 'bold' | 'title' | 'header' | 'wrap' | 'redBold';
export type XlsxValue = string | number | { v: string | number; s?: XlsxStyle };

const STYLE_INDEX: Record<XlsxStyle, number> = {
  normal: 0,
  bold: 1,
  title: 2,
  header: 3,
  wrap: 4,
  redBold: 5,
};

const enc = new TextEncoder();

const CRC_TABLE = (() => {
  const t = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c >>> 0;
  }
  return t;
})();

function crc32(bytes: Uint8Array): number {
  let c = 0xffffffff;
  for (let i = 0; i < bytes.length; i++) c = CRC_TABLE[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

/** Tên cột Excel: 0 → A, 25 → Z, 26 → AA. */
function colName(index: number): string {
  let n = index + 1;
  let s = '';
  while (n > 0) {
    const m = (n - 1) % 26;
    s = String.fromCharCode(65 + m) + s;
    n = Math.floor((n - 1) / 26);
  }
  return s;
}

const xmlEscape = (s: string) =>
  s
    .replace(/[\u0000-\u0008\u000B\u000C\u000E-\u001F]/g, '') // ký tự điều khiển không hợp lệ trong XML
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');

